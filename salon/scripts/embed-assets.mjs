// Bundles everything in public/ into the Worker (served by worker/static.js).
// Used instead of Workers Static Assets so a deploy is a single upload.
import fs from 'node:fs';
import path from 'node:path';
const ROOT = 'public', OUT = 'worker/.static';
fs.rmSync(OUT, { recursive: true, force: true }); fs.mkdirSync(OUT, { recursive: true });
const files = [];
(function walk(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); e.isDirectory() ? walk(p) : files.push(p); } })(ROOT);
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml', '.woff2': 'font/woff2', '.ico': 'image/x-icon' };
let imports = '', map = '';
files.forEach((f, i) => {
  fs.copyFileSync(f, `${OUT}/${i}.bin`);
  imports += `import f${i} from './.static/${i}.bin';\n`;
  map += `  ${JSON.stringify('/' + path.relative(ROOT, f).split(path.sep).join('/'))}: [f${i}, ${JSON.stringify(TYPES[path.extname(f)] || 'application/octet-stream')}],\n`;
});
fs.writeFileSync('worker/static.gen.js', `// Generated by scripts/embed-assets.mjs — do not edit\n${imports}export const FILES = {\n${map}};\nexport const VERSION = ${JSON.stringify(Date.now().toString(36))};\n`);
console.log(`embedded ${files.length} files`);
